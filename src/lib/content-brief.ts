import { KeywordItem } from './autocomplete';

export interface ContentBrief {
  title: string;
  seed: string;
  recommendedH1: string;
  recommendedH2s: string[];
  faqSection: { question: string; targetKeyword: string }[];
  primaryKeywords: string[];
  secondaryKeywords: string[];
  markdown: string;
}

export function generateContentBrief(seed: string, keywords: KeywordItem[]): ContentBrief {
  const topKeywords = [...keywords].sort((a, b) => b.relativeScore - a.relativeScore);
  const primary = topKeywords.slice(0, 5).map((k) => k.keyword);
  const secondary = topKeywords.slice(5, 20).map((k) => k.keyword);

  // STRICT 100% REAL AUTOCOMPLETE QUESTIONS ONLY:
  // Must match genuine question prefixes from Google Autocomplete or question-* sources.
  // Zero synthetic text, zero template prefixes added.
  const questionKeywords = topKeywords.filter((k) =>
    /^(how|what|why|where|when|who|which|can|is|are|does|do|should|will)\b/i.test(k.keyword) ||
    k.sources.some((s) => s.startsWith('question-'))
  ).slice(0, 6);

  // Extract commercial and review keywords for H2 subheadings
  const commercialKeywords = topKeywords.filter((k) =>
    k.intent === 'commercial' || k.intent === 'transactional' || /(best|top|vs|guide|tips|how to|review|alternative|generator|creator)/i.test(k.keyword)
  ).slice(0, 6);

  const cleanSeedTitle = seed.charAt(0).toUpperCase() + seed.slice(1);
  const recommendedH1 = `The Complete Guide to ${cleanSeedTitle}: Best Practices & Strategies`;

  const recommendedH2s = [
    `What is ${cleanSeedTitle}? (Overview & Fundamentals)`,
    ...commercialKeywords.map((k) => `## ${k.keyword.charAt(0).toUpperCase() + k.keyword.slice(1)}`),
    `Key Benefits & Best Practices for ${cleanSeedTitle}`,
  ];

  const faqList = questionKeywords.map((k) => {
    const q = k.keyword.trim();
    const formatted = q.charAt(0).toUpperCase() + q.slice(1);
    return {
      question: formatted.endsWith('?') ? formatted : `${formatted}?`,
      targetKeyword: k.keyword,
    };
  });

  const markdown = `# SEO Content Brief: ${cleanSeedTitle}

## 🎯 Target Overview
- **Primary Seed Query**: \`${seed}\`
- **Recommended H1**: ${recommendedH1}
- **Target Audience Intent**: Informational & Commercial

---

## 🔑 Keyword Targets
### Primary Focus Keywords (Top Relative Score)
${primary.map((k) => `- **${k}**`).join('\n')}

### Secondary & Long-Tail Keywords
${secondary.map((k) => `- ${k}`).join('\n')}

---

## 📑 Proposed Article Structure
${recommendedH2s.map((h2, i) => `### Section [${i + 1}]: ${h2}\n*Notes: Target relevant sub-queries and provide actionable examples.*`).join('\n\n')}

${faqList.length > 0 ? `---

## ❓ Recommended FAQs (Google Autocomplete Questions)
${faqList.map((f) => `### Q: ${f.question}\n**Targeting Query**: \`${f.targetKeyword}\`\n*Answer guidance: Provide a direct, concise 2-sentence answer for Google Featured Snippets.*`).join('\n\n')}` : ''}

---
*Generated by Google Keyword Dominator (GKD) • 100% Real Autocomplete Data*
`;

  return {
    title: `SEO Brief: ${cleanSeedTitle}`,
    seed,
    recommendedH1,
    recommendedH2s,
    faqSection: faqList,
    primaryKeywords: primary,
    secondaryKeywords: secondary,
    markdown,
  };
}
