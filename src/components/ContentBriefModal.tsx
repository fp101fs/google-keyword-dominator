'use client';

import React, { useState, useEffect } from 'react';
import { KeywordItem } from '@/lib/autocomplete';
import { X, Copy, Check, FileText, Sparkles, HelpCircle, Layers, Gauge, Loader2, Globe } from 'lucide-react';
import { PageGraderDrawer } from './PageGraderDrawer';
import { LlmBriefResponse } from '@/lib/llm';
import { SiteContextProfile } from '@/lib/intelligence/site-context';

interface ContentBriefModalProps {
  seed: string;
  keywords: KeywordItem[];
  isOpen: boolean;
  onClose: () => void;
  siteUrl?: string;
}

export const ContentBriefModal: React.FC<ContentBriefModalProps> = ({
  seed,
  keywords,
  isOpen,
  onClose,
  siteUrl,
}) => {
  const [copied, setCopied] = useState(false);
  const [isGraderOpen, setIsGraderOpen] = useState(false);
  const [isLoadingLlm, setIsLoadingLlm] = useState(false);
  const [llmData, setLlmData] = useState<LlmBriefResponse | null>(null);
  const [siteContext, setSiteContext] = useState<SiteContextProfile | null>(null);

  useEffect(() => {
    if (!isOpen || !seed || keywords.length === 0) return;

    let isMounted = true;

    async function loadBrief() {
      setIsLoadingLlm(true);
      try {
        let loadedContext: SiteContextProfile | null = null;

        // Auto-fetch site context if siteUrl is present
        if (siteUrl && siteUrl.trim()) {
          try {
            const ctxRes = await fetch('/api/site-context', {
              method: 'POST',
              headers: { 'Content-Type': 'application/json' },
              body: JSON.stringify({ url: siteUrl }),
            });
            const ctxData = await ctxRes.json();
            if (ctxData.success && ctxData.profile) {
              loadedContext = ctxData.profile;
              if (isMounted) setSiteContext(ctxData.profile);
            }
          } catch {
            // Non-blocking fallback
          }
        }

        const res = await fetch('/api/content-brief', {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({
            seed,
            keywords,
            siteContext: loadedContext
              ? {
                  siteName: loadedContext.siteName,
                  businessType: loadedContext.businessType,
                  targetAudience: loadedContext.targetAudience,
                  situationalSummary: loadedContext.situationalSummary,
                }
              : undefined,
          }),
        });
        const data = await res.json();
        if (isMounted && data.success && data.llmData) {
          setLlmData(data.llmData);
        }
      } catch (err) {
        console.error('Failed to load LLM brief:', err);
      } finally {
        if (isMounted) setIsLoadingLlm(false);
      }
    }

    loadBrief();

    return () => {
      isMounted = false;
    };
  }, [isOpen, seed, keywords, siteUrl]);

  if (!isOpen) return null;

  // Primary Focus Keywords (Top 5 genuine search terms)
  const primaryKeywords = keywords.slice(0, 5);

  // Raw Google question queries
  const questionKeywords = keywords.filter((k) =>
    /^(how|what|why|can|is|are|which|where|does|do|should|will|who)\b/i.test(k.keyword) ||
    k.sources.some((s) => s.startsWith('question-'))
  ).slice(0, 6);

  // Raw Google commercial queries
  const secondaryKeywords = keywords.filter((k) =>
    k.intent === 'commercial' || k.intent === 'transactional' || /(best|top|vs|guide|tips|how to|review|alternative|generator|creator)/i.test(k.keyword)
  ).slice(0, 6);

  const h1Title = llmData?.suggestedH1 || `Complete Guide to ${seed}`;
  const h2List = llmData?.recommendedH2s || secondaryKeywords.map((k) => k.keyword);
  const faqList = llmData?.recommendedFaqs || questionKeywords.map((k) => ({
    question: k.keyword,
    answerSnippet: 'Direct answer snippet answering the query.',
  }));

  const markdownContent = `# ${h1Title}

## Target Seed Keyword
- **Seed Keyword:** \`${seed}\`
${siteContext ? `- **Business Context:** ${siteContext.siteName} (${siteContext.businessType}) - ${siteContext.targetAudience}` : ''}
${llmData?.contentAngle ? `- **Content Angle:** ${llmData.contentAngle}\n- **Target Audience:** ${llmData.targetAudience}` : ''}

## Primary Keywords to Include
${primaryKeywords.map((kw) => `- [ ] ${kw.keyword}`).join('\n')}

## Recommended H2 Article Outline
${h2List.map((h2) => `## ${h2}`).join('\n')}

## Recommended FAQs & Schema Ready Answers
${faqList.map((faq) => `### Q: ${faq.question}\n${faq.answerSnippet}`).join('\n\n')}

---
*Generated by Google Keyword Dominator (GKD) with DeepSeek AI & Live Search Grounding*
`;

  const handleCopyMarkdown = async () => {
    await navigator.clipboard.writeText(markdownContent);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <>
      <div className="fixed inset-0 z-50 bg-slate-950/70 backdrop-blur-xs flex items-center justify-center p-4 overflow-y-auto animate-fadeIn">
        <div className="bg-white rounded-2xl max-w-2xl w-full shadow-2xl border border-slate-200 overflow-hidden flex flex-col max-h-[90vh]">
          {/* Modal Header */}
          <div className="p-4 sm:p-6 border-b border-slate-100 flex items-center justify-between bg-gradient-to-r from-blue-900 via-indigo-900 to-slate-900 text-white">
            <div className="flex items-center gap-3">
              <div className="p-2 bg-blue-500/20 border border-blue-400/30 text-blue-300 rounded-xl shadow-inner">
                <FileText className="w-5 h-5" />
              </div>
              <div>
                <h3 className="text-base sm:text-lg font-bold text-white flex items-center gap-2">
                  1-Click AI Content Brief
                  <span className="text-[10px] bg-blue-500 text-white font-extrabold px-2 py-0.5 rounded-full">
                    DeepSeek AI
                  </span>
                </h3>
                <p className="text-xs text-blue-200">
                  Target Seed: <strong className="text-white font-semibold">{seed || 'Seed Topic'}</strong>
                </p>
              </div>
            </div>
            <button
              onClick={onClose}
              className="p-2 text-slate-400 hover:text-white hover:bg-white/10 rounded-lg transition-colors cursor-pointer"
            >
              <X className="w-5 h-5" />
            </button>
          </div>

          {/* Modal Body */}
          <div className="p-4 sm:p-6 overflow-y-auto space-y-6 flex-1 text-sm bg-slate-50/50">
            {isLoadingLlm ? (
              <div className="p-10 text-center space-y-3 bg-white rounded-2xl border border-slate-200">
                <Loader2 className="w-7 h-7 animate-spin text-blue-600 mx-auto" />
                <p className="text-xs font-bold text-slate-700">Synthesizing SEO Content Architecture via DeepSeek AI...</p>
              </div>
            ) : (
              <>
                {/* Site Context Badge if present */}
                {siteContext && (
                  <div className="p-3 bg-blue-50 border border-blue-200 rounded-xl flex items-center justify-between gap-2 text-xs">
                    <div className="flex items-center gap-2 text-blue-900">
                      <Globe className="w-4 h-4 text-blue-600 shrink-0" />
                      <span>
                        Tailored for <strong className="font-bold">{siteContext.siteName}</strong> ({siteContext.businessType})
                      </span>
                    </div>
                    {siteContext.discoveredUrlsCount > 0 && (
                      <span className="text-[10px] font-mono font-bold bg-white text-blue-700 px-2 py-0.5 rounded border border-blue-200">
                        {siteContext.discoveredUrlsCount} sitemap URLs
                      </span>
                    )}
                  </div>
                )}

                {/* Suggested Title */}
                <div className="space-y-1.5 p-4 bg-white rounded-xl border border-slate-200 shadow-2xs">
                  <span className="text-xs font-bold uppercase tracking-wider text-blue-700 block flex items-center gap-1">
                    <Sparkles className="w-3.5 h-3.5" />
                    AI-Optimized H1 Title
                  </span>
                  <div className="font-extrabold text-slate-900 text-base">{h1Title}</div>
                  {llmData?.contentAngle && (
                    <p className="text-xs text-slate-500 pt-1">
                      <strong className="text-slate-700">Angle:</strong> {llmData.contentAngle}
                    </p>
                  )}
                </div>

                {/* Core Checklist */}
                <div className="space-y-2">
                  <span className="text-xs font-bold uppercase tracking-wider text-slate-500 block flex items-center gap-1">
                    <Layers className="w-3.5 h-3.5" />
                    Primary Keywords to Include
                  </span>
                  <div className="grid grid-cols-1 sm:grid-cols-2 gap-2">
                    {primaryKeywords.map((kw, i) => (
                      <div key={i} className="flex items-center gap-2 p-2 bg-white rounded-lg border border-slate-200 text-xs font-semibold text-slate-700">
                        <span className="w-2 h-2 rounded-full bg-blue-500 shrink-0" />
                        <span className="truncate">{kw.keyword}</span>
                      </div>
                    ))}
                  </div>
                </div>

                {/* H2 Subheadings */}
                <div className="space-y-2">
                  <span className="text-xs font-bold uppercase tracking-wider text-slate-500 block">
                    Recommended H2 Subheadings &amp; Outline
                  </span>
                  <div className="space-y-1.5">
                    {h2List.map((h2, i) => (
                      <div key={i} className="p-3 bg-white rounded-lg border border-slate-200 text-xs text-slate-900 font-bold">
                        ## {h2}
                      </div>
                    ))}
                  </div>
                </div>

                {/* FAQ Questions */}
                {faqList.length > 0 && (
                  <div className="space-y-3">
                    <span className="text-xs font-bold uppercase tracking-wider text-slate-500 block flex items-center gap-1">
                      <HelpCircle className="w-3.5 h-3.5" />
                      Recommended FAQs &amp; Schema Ready Answers
                    </span>
                    <div className="space-y-2">
                      {faqList.map((faq, i) => (
                        <div key={i} className="p-3.5 bg-white rounded-xl border border-slate-200 space-y-1.5 text-xs">
                          <div className="font-extrabold text-slate-900 flex items-start gap-1.5">
                            <span className="text-blue-600 font-black">Q:</span>
                            <span>{faq.question}</span>
                          </div>
                          <p className="text-slate-600 pl-4 leading-relaxed text-[11px]">
                            {faq.answerSnippet}
                          </p>
                        </div>
                      ))}
                    </div>
                  </div>
                )}
              </>
            )}
          </div>

          {/* Modal Footer */}
          <div className="p-4 bg-white border-t border-slate-200 flex items-center justify-between">
            <button
              onClick={() => setIsGraderOpen(true)}
              className="px-3.5 py-2 bg-indigo-50 hover:bg-indigo-100 text-indigo-700 border border-indigo-200 rounded-xl text-xs font-bold flex items-center gap-1.5 transition-colors cursor-pointer"
            >
              <Gauge className="w-4 h-4 text-indigo-600" />
              <span>Grade Live Page (0-100 SEO)</span>
            </button>

            <div className="flex items-center gap-2">
              <button
                onClick={onClose}
                className="px-3.5 py-2 bg-white border border-slate-300 hover:bg-slate-100 text-slate-700 rounded-xl text-xs font-bold cursor-pointer transition-colors"
              >
                Close
              </button>
              <button
                onClick={() => {
                  const blob = new Blob([markdownContent], { type: 'text/markdown;charset=utf-8' });
                  const url = URL.createObjectURL(blob);
                  const a = document.createElement('a');
                  a.href = url;
                  a.download = `content-brief-${seed.toLowerCase().replace(/[^a-z0-9]+/g, '-')}.md`;
                  document.body.appendChild(a);
                  a.click();
                  document.body.removeChild(a);
                  URL.revokeObjectURL(url);
                }}
                className="px-3.5 py-2 bg-slate-100 hover:bg-slate-200 text-slate-800 border border-slate-300 rounded-xl text-xs font-bold flex items-center gap-1.5 cursor-pointer transition-colors"
                title="Download as Markdown file for Notion/Obsidian"
              >
                <FileText className="w-3.5 h-3.5 text-slate-600" />
                <span>Download .md</span>
              </button>
              <button
                onClick={handleCopyMarkdown}
                className="px-4 py-2 bg-slate-900 hover:bg-slate-800 text-white rounded-xl text-xs font-bold flex items-center gap-1.5 shadow-md cursor-pointer transition-colors"
              >
                {copied ? <Check className="w-4 h-4 text-emerald-400" /> : <Copy className="w-4 h-4" />}
                <span>{copied ? 'Copied' : 'Copy Markdown'}</span>
              </button>
            </div>
          </div>
        </div>
      </div>

      {/* 1-Click Page Grader Drawer */}
      <PageGraderDrawer
        isOpen={isGraderOpen}
        onClose={() => setIsGraderOpen(false)}
        targetKeyword={seed}
      />
    </>
  );
};
